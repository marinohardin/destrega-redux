"""The "Destrega Redux: Marino's Build" caption drawn over the KOEI logo movie (runtime/splash.c).

Original text art only: two lines of text in a macOS system font (Helvetica Neue italic, close to
the movie's own "KOEI PRESENTS" lettering) with a soft dark shadow. No game data is used.

The result is committed as runtime/splash_text.h (width, height and the zlib-compressed
luminance + alpha planes), so building needs nothing; rerun this only to change the caption.
Needs macOS (for the font) and Pillow.

usage: python3 tools/make_splash_text.py runtime/splash_text.h [--png preview.png]
"""
import sys
import zlib

from PIL import Image, ImageChops, ImageDraw, ImageFilter, ImageFont

OUT = sys.argv[1]
PNG = sys.argv[sys.argv.index("--png") + 1] if "--png" in sys.argv else None
FONT = "/System/Library/Fonts/HelveticaNeue.ttc"
LINES = [("DESTREGA REDUX", 11, 132, 10), ("MARINO\u2019S BUILD", 8, 78, 14)]   # text, face, px, tracking
GAP, PAD, SS = 26, 40, 2


def line_image(text, face, px, track):
    f = ImageFont.truetype(FONT, px * SS, index=face)
    widths = [f.getlength(c) for c in text]
    w = int(sum(widths) + track * SS * (len(text) - 1)) + 8 * SS
    asc, desc = f.getmetrics()
    im = Image.new("L", (w, asc + desc), 0)
    d, x = ImageDraw.Draw(im), 0.0
    for c, cw in zip(text, widths):
        d.text((x, 0), c, font=f, fill=255)
        x += cw + track * SS
    return im.crop(im.getbbox())


ims = [line_image(*l) for l in LINES]
W = max(i.width for i in ims) + 2 * PAD * SS
H = sum(i.height for i in ims) + GAP * SS * (len(ims) - 1) + 2 * PAD * SS
text = Image.new("L", (W, H), 0)
y = PAD * SS
for i in ims:
    text.paste(i, ((W - i.width) // 2, y))
    y += i.height + GAP * SS
text = text.resize((W // SS, H // SS), Image.LANCZOS)
shadow = ImageChops.offset(text, 3, 4).filter(ImageFilter.GaussianBlur(6))
shadow = shadow.point(lambda v: min(255, v * 2) * 0.85)
alpha = ImageChops.lighter(text, shadow.point(int))
# luminance: white text over a black shadow (premultiplied by alpha below on the runtime side)
lum = Image.new("L", text.size, 0)
lum.paste(255, mask=text)
planes = bytes(lum.tobytes()) + bytes(alpha.tobytes())
comp = zlib.compress(planes, 9)
with open(OUT, "w") as o:
    o.write("/* generated by tools/make_splash_text.py: the splash caption (original text art, no game\n"
            " * data); luminance plane then alpha plane, zlib-compressed. Do not edit. */\n")
    o.write(f"#define SPLASH_TEXT_W {text.width}\n#define SPLASH_TEXT_H {text.height}\n")
    o.write(f"#define SPLASH_TEXT_ZLEN {len(comp)}\n")
    o.write("static const unsigned char k_splash_text_z[] = {\n")
    for i in range(0, len(comp), 20):
        o.write("    " + ", ".join(str(b) for b in comp[i:i + 20]) + ",\n")
    o.write("};\n")
if PNG:
    bg = Image.new("RGB", text.size, (40, 40, 40))
    bg.paste(Image.merge("RGB", (lum, lum, lum)), mask=alpha)
    bg.save(PNG)
print(f"{OUT}: {text.width}x{text.height}, {len(comp)} bytes compressed")
