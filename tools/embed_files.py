#!/usr/bin/env python3
"""Embed what the launcher needs to build the game module into the executable.

    embed_files.py ROOT OUT_DIR

Writes OUT_DIR/game_sdk.h and OUT_DIR/game_sdk_files.c:

- the module SDK: the runtime headers the generated code is compiled against (psx.h, recomp.h,
  pgxp.h, game_abi.h, game_module_side.h) and the module glue game_module.c;
- the recompiler's analysis inputs (analysis/*.txt seeds / overrides / idle loops / widescreen
  culling points and the REA procedure lists), exactly the files recomp/recomp.py reads.

GAME_ABI_SDK_ID is the sha256 of the SDK files (the runtime refuses a module compiled from other
headers); GAME_RECOMP_ID the sha256 of the C recompiler's source (runtime/launcher/recompiler.[ch]).
Both are part of the launcher's module key (runtime/launcher/launcher.c), which also hashes the
analysis inputs it uses, so any change to what the generated code would be rebuilds the module. Line endings are normalised to LF so the
ids are the same on every platform. Outputs are only rewritten when they change.
"""
import hashlib
import os
import sys

SDK = ["runtime/psx.h", "runtime/recomp.h", "runtime/pgxp.h", "runtime/game_abi.h",
       "runtime/game_module_side.h", "runtime/game_module.c"]
ANALYSIS_TXT = ["extra_seeds.txt", "overrides.txt", "idle_loops.txt", "widescreen_cull.txt"]
RECOMPILER = ["runtime/launcher/recompiler.c", "runtime/launcher/recompiler.h"]


def read(root, rel):
    with open(os.path.join(root, rel), "rb") as f:
        return f.read().replace(b"\r\n", b"\n")


def c_string(data):
    out, line = [], []
    for b in data:
        if b == 0x5c:
            line.append("\\\\")
        elif b == 0x22:
            line.append('\\"')
        elif b == 0x0a:
            line.append("\\n")
            out.append('"' + "".join(line) + '"')
            line = []
            continue
        elif 0x20 <= b < 0x7f and b != 0x3f:   # '?' avoided: trigraphs
            line.append(chr(b))
        else:
            line.append("\\%03o" % b)
        if len(line) > 200:
            out.append('"' + "".join(line) + '"')
            line = []
    if line or not out:
        out.append('"' + "".join(line) + '"')
    return "\n    ".join(out)


def write_if_changed(path, text):
    try:
        with open(path, encoding="utf-8") as f:
            if f.read() == text:
                return
    except OSError:
        pass
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.replace(tmp, path)


def main():
    root, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    files = []   # (embedded name, data, kind)
    for rel in SDK:
        files.append(("sdk/" + os.path.basename(rel), read(root, rel), 0))
    analysis = [r for r in ANALYSIS_TXT if os.path.exists(os.path.join(root, "analysis", r))]
    analysis.append("rea_list_procedures_main.json")
    ovl = os.path.join(root, "analysis", "overlays")
    analysis += sorted("overlays/" + n for n in os.listdir(ovl) if n.endswith(".procs.json"))
    for rel in analysis:
        files.append(("analysis/" + rel, read(root, "analysis/" + rel), 1))

    sdk = hashlib.sha256()
    for name, data, kind in files:
        if kind == 0:
            sdk.update(name.encode() + b"\0" + data + b"\0")
    inputs = hashlib.sha256()
    for rel in RECOMPILER:
        inputs.update(rel.encode() + b"\0" + read(root, rel) + b"\0")

    write_if_changed(os.path.join(out, "game_sdk.h"),
                     "/* Generated by tools/embed_files.py - do not edit. */\n#pragma once\n"
                     f'#define GAME_ABI_SDK_ID "{sdk.hexdigest()}"\n'
                     f'#define GAME_RECOMP_ID "{inputs.hexdigest()}"\n')
    c = ["/* Generated by tools/embed_files.py - do not edit. */",
         '#include "launcher/embedded.h"', ""]
    for i, (name, data, _) in enumerate(files):
        c.append(f"static const char f{i}[] =\n    {c_string(data)};")
    c.append("")
    c.append("const EmbeddedFile g_embedded_files[] = {")
    for i, (name, data, kind) in enumerate(files):
        c.append(f'    {{"{name}", f{i}, {len(data)}, {kind}}},')
    c.append("};")
    c.append(f"const int g_embedded_count = {len(files)};")
    write_if_changed(os.path.join(out, "game_sdk_files.c"), "\n".join(c) + "\n")


if __name__ == "__main__":
    main()
