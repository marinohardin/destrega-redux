#!/usr/bin/env python3
"""Compile runtime/shaders/hires.glsl to SPIR-V and write runtime/shaders/hires_spirv.h.

The SDL_GPU hi-res backend (runtime/hires_gpu.c) embeds the SPIR-V for Vulkan (Windows,
Linux; MoltenVK on macOS with --gpu-driver vulkan) next to its MSL source for Metal. The
header is checked in (generated shader bytecode, not game data), so building the game needs
no shader compiler. Run this after editing hires.glsl:

    python3 tools/gen_spirv.py            # regenerate the header
    python3 tools/gen_spirv.py --check    # compile + validate only (CI); exit 1 on errors

Needs glslangValidator (glslang) and, if present, spirv-val (SPIRV-Tools) on PATH.
"""
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'runtime', 'shaders', 'hires.glsl')
OUT = os.path.join(ROOT, 'runtime', 'shaders', 'hires_spirv.h')
# (array name, -D define, glslang stage)
ENTRIES = [
    ('s_spv_vs_prim', 'VS_PRIM', 'vert'),
    ('s_spv_fs_prim', 'FS_PRIM', 'frag'),
    ('s_spv_vs_full', 'VS_FULL', 'vert'),
    ('s_spv_fs_present', 'FS_PRESENT', 'frag'),
]


def tool(name):
    p = shutil.which(name)
    if not p:
        sys.exit(f'gen_spirv: {name} not found on PATH (install glslang / SPIRV-Tools)')
    return p


def compile_all(tmp):
    glslang = tool('glslangValidator')
    val = shutil.which('spirv-val')
    blobs = []
    for name, define, stage in ENTRIES:
        spv = os.path.join(tmp, name + '.spv')
        cmd = [glslang, '-V', '--target-env', 'vulkan1.0', '-S', stage, '-D' + define, '-o', spv, SRC]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            sys.exit(f'gen_spirv: {define}: glslangValidator failed\n{r.stdout}{r.stderr}')
        if val:
            r = subprocess.run([val, '--target-env', 'vulkan1.0', spv], capture_output=True, text=True)
            if r.returncode:
                sys.exit(f'gen_spirv: {define}: spirv-val failed\n{r.stdout}{r.stderr}')
        with open(spv, 'rb') as f:
            blobs.append((name, define, f.read()))
    ver = subprocess.run([glslang, '--version'], capture_output=True, text=True).stdout.splitlines()
    return blobs, (ver[0].strip() if ver else 'glslangValidator'), bool(val)


def main():
    check = '--check' in sys.argv[1:]
    with tempfile.TemporaryDirectory() as tmp:
        blobs, ver, validated = compile_all(tmp)
    if check:
        for name, define, b in blobs:
            print(f'gen_spirv: {define}: {len(b)} bytes OK{" (spirv-val)" if validated else ""}')
        return
    lines = ['/* Generated by tools/gen_spirv.py from runtime/shaders/hires.glsl - do not edit.',
             f' * {ver}, --target-env vulkan1.0. */', '#pragma once', '']
    for name, define, b in blobs:
        lines.append(f'/* {define} */')
        lines.append(f'static const unsigned char {name}[{len(b)}] = {{')
        for i in range(0, len(b), 20):
            lines.append('    ' + ', '.join(f'0x{x:02x}' for x in b[i:i + 20]) + ',')
        lines.append('};')
        lines.append('')
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines))
    print(f'gen_spirv: wrote {os.path.relpath(OUT, ROOT)} ({", ".join(f"{d} {len(b)}" for _, d, b in blobs)} bytes)')


if __name__ == '__main__':
    main()
