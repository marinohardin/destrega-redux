#!/usr/bin/env python3
"""Emulation source identity for netplay: one 32-bit hash of the source files that decide what
the emulated machine does, written as a C header (`source_ident.h`, DESTREGA_SOURCE_IDENT).

Two players can only play together if both emulate exactly the same machine. The netplay
handshake compares this hash, the recompiled-code table (replay_build_id: which game functions
were recompiled from which original bytes) and the disc. The rule:

  - covered: the emulation runtime (runtime/*.c|h, runtime/overrides/), the recompiler that
    turns the game's code into C (recomp/*.py) and its inputs in analysis/ (seeds, overrides,
    overlay and procedure lists). A change to any of them can change emulated behaviour, so
    builds that differ there are refused, even if the change looks harmless.
  - not covered: what only one platform compiles or what is presentation only and proven not to
    reach emulated state (native menus, the platform shims, the hi-res / GPU renderers and their
    shaders, Windows resources), the input layer and settings file (host keys -> pad bits; the
    bits are what netplay exchanges), plus tools, tests and docs. A Mac and a Windows build of the
    same commit therefore agree, and so do builds that differ only in those files.
  - contents are hashed with line endings normalised (CR LF -> LF), so a Windows checkout with
    core.autocrlf hashes like a Unix one. The compiler, OS and build type are not part of it:
    the per-frame state hashes of the Mac (clang) and Windows (MinGW GCC) builds are identical
    (tools/test_wine.sh, tools/test_netplay_wine.py), so they emulate the same machine.

Usage: source_ident.py ROOT OUT.h        (also prints the file list with --list)
"""
import hashlib
import os
import sys

EXCLUDE = {
    "runtime/menu_mac.m", "runtime/menu_win.c", "runtime/menu_stub.c", "runtime/menu.h",
    "runtime/platform.c", "runtime/platform_net.c", "runtime/platform.h",
    "runtime/hires.c", "runtime/hires.h", "runtime/hires_gpu.c", "runtime/hires_gpu.h",
    # host input -> pad bits and the settings file: they decide which key or controller button
    # sets which pad bit on this machine, never what the emulated machine does with the bits
    # (netplay exchanges the bits themselves, replays record them)
    "runtime/input.c", "runtime/input.h", "runtime/settings.c", "runtime/settings.h",
    "runtime/controls_mac.m", "runtime/controls_win.c",
    # automatic port forwarding for the host (router protocols on a worker thread): it only talks
    # to the router and shows an address, never touches emulated state
    "runtime/portmap.c", "runtime/portmap.h",
    # Netplay menu / panel text, the copy actions and the parsing of typed addresses: they read
    # netplay.c's state for display and call the same host / join entry points, never emulated state
    # or the protocol
    "runtime/netplay_ui.c", "runtime/netplay_ui.h",
    # smoothness statistics and the render-scale governor: host timing in, a hi-res render scale and
    # a load figure for the status line out; never emulated state (tools/test_governor.py compares
    # every frame's state hash with a plain run)
    "runtime/smooth.c", "runtime/smooth.h",
}


def files(root):
    out = []
    for d, exts in (("runtime", (".c", ".h")), ("runtime/overrides", (".c", ".h")),
                    ("recomp", (".py",)), ("analysis/overlays", None)):
        p = os.path.join(root, d)
        if not os.path.isdir(p):
            continue
        for n in sorted(os.listdir(p)):
            rel = d + "/" + n
            if not os.path.isfile(os.path.join(root, rel)) or rel in EXCLUDE:
                continue
            if n.startswith("test_") or (exts and not n.endswith(exts)):
                continue
            out.append(rel)
    for rel in ("analysis/extra_seeds.txt", "analysis/overrides.txt", "analysis/widescreen_cull.txt",
                "analysis/idle_loops.txt", "analysis/rea_list_procedures_main.json"):
        if os.path.isfile(os.path.join(root, rel)):
            out.append(rel)
    return sorted(out)


def ident(root):
    h = hashlib.sha256()
    for rel in files(root):
        with open(os.path.join(root, rel), "rb") as f:
            data = f.read().replace(b"\r\n", b"\n")
        h.update(rel.encode() + b"\0" + str(len(data)).encode() + b"\0" + data)
    return int.from_bytes(h.digest()[:4], "little")


def main():
    if len(sys.argv) >= 2 and sys.argv[1] == "--list":
        print("\n".join(files(sys.argv[2] if len(sys.argv) > 2 else ".")))
        return
    root, out = sys.argv[1], sys.argv[2]
    text = ("/* generated by tools/source_ident.py: emulation source identity (netplay handshake) */\n"
            "#define DESTREGA_SOURCE_IDENT 0x%08xu\n" % ident(root))
    try:
        with open(out) as f:
            if f.read() == text:
                return
    except OSError:
        pass
    with open(out, "w", newline="\n") as f:
        f.write(text)


if __name__ == "__main__":
    main()
